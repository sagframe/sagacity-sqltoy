/**
 * @project sagacity-sqltoy
 * @description SAP HANA 2.0数据库方言实现(HANA Express 2.0 SPS08实库验证)。
 *              HANA语法近oracle:nvl/merge into/sequence.nextval/dummy虚表/未加引号标识符
 *              大写存储/for update wait n锁;差异部分: 1、分页为标准offset ? rows fetch next ?
 *              rows only(复用OracleDialectUtils) 2、随机数为order by rand() limit
 *              n(无dbms_random/rownum,复用DefaultDialectUtils) 3、跳过已锁行为for update
 *              ignore(无skip locked语法,见HanaDialectUtils)
 *              4、表/列备注取SYS.TABLES/SYS.VIEWS/SYS.TABLE_COLUMNS的COMMENTS(无user_tab_comments)
 *              5、identity为原生GENERATED BY DEFAULT AS
 *              IDENTITY(无需oracle式转sequence)
 *              6、无原生json列类型(json文档以NVARCHAR/NCLOB承载,裸?+setString)
 * @author zhongxuchen
 * @version v1.0,Date:2026-09-11
 */
